using System.Net;
using System.Text;
using Aspose.Pdf;
using TenderSystem.Areas.Shared.Models.Reports;
using TenderSystem.Services.Files;

namespace TenderSystem.Services.Reports;

public class ReportPdfWriter
{
    public async Task<byte[]> WriteAsync(ReportPageViewModel page, string webRootPath, CancellationToken ct)
    {
        var table = ReportTable.Create(page);
        var html = new StringBuilder("<html><head><meta charset='utf-8'><style>body{font-family:Arial;font-size:11px;color:inherit}h1{font-size:24px}h2{font-size:15px;margin:0 0 6px}p{margin:4px 0}section{border:1px solid;padding:12px;margin-bottom:12px;page-break-inside:avoid}table{width:100%;table-layout:fixed;border-collapse:collapse}td{width:33.33%;vertical-align:top;padding:6px;word-wrap:break-word}small{font-size:10px}</style></head><body>");
        html.Append("<h1>").Append(Text(page.Selected?.Title ?? "Report")).Append("</h1>");
        html.Append("<p>Generated by ").Append(Text(page.GeneratedBy)).Append(" | ")
            .Append(page.GeneratedAt.ToString("dd MMM yyyy, HH:mm")).Append(" UTC</p>");
        html.Append("<p>").Append(page.TotalCount).Append(" matching records</p><br>");
        for (var r = 0; r < page.Rows.Count; r++)
        {
            ct.ThrowIfCancellationRequested();
            var record = page.Rows[r];
            html.Append("<section><h2>").Append(Text(record.Reference)).Append("</h2>");
            if (record.Title != record.Reference) html.Append("<p>").Append(Text(record.Title)).Append("</p>");
            html.Append("<p><b>").Append(Text(record.Status)).Append("</b></p>");
            if (!string.IsNullOrEmpty(record.TenderNumber) && record.TenderNumber != record.Reference)
                html.Append("<p>Tender: ").Append(Text(record.TenderNumber)).Append("</p>");
            var fields = new List<ReportFieldViewModel>();
            for (var c = 1; c < table.Headers.Count; c++)
                if (table.Headers[c] != "Status" && !string.IsNullOrWhiteSpace(table.Rows[r][c]))
                    fields.Add(new ReportFieldViewModel { Label = table.Headers[c], Value = table.Rows[r][c] });
            fields.AddRange(record.MoreDetails);
            html.Append("<table>");
            for (var i = 0; i < fields.Count; i += 3)
            {
                html.Append("<tr>");
                for (var c = 0; c < 3; c++)
                {
                    html.Append("<td>");
                    if (i + c < fields.Count)
                        html.Append("<small>").Append(Text(fields[i + c].Label)).Append("</small><p>")
                            .Append(Text(fields[i + c].Value)).Append("</p>");
                    html.Append("</td>");
                }
                html.Append("</tr>");
            }
            html.Append("</table></section>");
        }
        if (page.Rows.Count == 0) html.Append("<p>No records match these filters.</p>");
        html.Append("</body></html>");
        using var input = new MemoryStream(Encoding.UTF8.GetBytes(html.ToString()));
        var options = new HtmlLoadOptions();
        options.PageInfo.Width = 842;
        options.PageInfo.Height = 595;
        options.PageInfo.Margin = new MarginInfo(34, 105, 34, 34);
        using var document = new Document(input, options);
        // The currently installed evaluation library can process the first four pages only.
        using var preview = new Document();
        for (var i = 1; i <= Math.Min(4, document.Pages.Count); i++) preview.Pages.Add(document.Pages[i]);
        using var pdf = new MemoryStream();
        preview.Save(pdf);
        pdf.Position = 0;
        return await DocumentWatermarkService.CreateWatermarkedCopyAsync(pdf, "report.pdf", page.GeneratedBy,
            page.GeneratedAt, webRootPath, ct);
    }

    private static string Text(string value) => WebUtility.HtmlEncode(value).Replace("\r\n", "\n").Replace("\n", "<br>");
}
