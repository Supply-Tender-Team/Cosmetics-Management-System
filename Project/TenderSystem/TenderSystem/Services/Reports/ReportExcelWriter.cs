using System.Globalization;
using DocumentFormat.OpenXml;
using DocumentFormat.OpenXml.Packaging;
using DocumentFormat.OpenXml.Spreadsheet;
using TenderSystem.Areas.Shared.Models.Reports;

namespace TenderSystem.Services.Reports;

public class ReportExcelWriter
{
    public byte[] Write(ReportPageViewModel page)
    {
        var table = ReportTable.Create(page, true);
        using var stream = new MemoryStream();
        using (var document = SpreadsheetDocument.Create(stream, SpreadsheetDocumentType.Workbook))
        {
            var workbook = document.AddWorkbookPart(); workbook.Workbook = new Workbook();
            var styles = workbook.AddNewPart<WorkbookStylesPart>();
            styles.Stylesheet = new Stylesheet(new Fonts(new Font(), new Font(new Bold())),
                new Fills(new Fill(new PatternFill { PatternType = PatternValues.None }), new Fill(new PatternFill { PatternType = PatternValues.Gray125 })),
                new Borders(new Border()), new CellStyleFormats(new CellFormat()),
                new CellFormats(new CellFormat(), new CellFormat { FontId = 1, ApplyFont = true }, new CellFormat { Alignment = new Alignment { WrapText = true, Vertical = VerticalAlignmentValues.Top }, ApplyAlignment = true }));
            var part = workbook.AddNewPart<WorksheetPart>(); var data = new SheetData();
            var columns = new Columns();
            for (var i = 0; i < table.Headers.Count; i++)
                columns.Append(new Column { Min = (uint)i + 1, Max = (uint)i + 1, Width = table.Headers[i] == "Additional details" ? 65 : i < 2 ? 45 : 23, CustomWidth = true });
            part.Worksheet = new Worksheet(columns, data);
            AddTextRow(data, new[] { page.Selected?.Title ?? "Report" }, 1);
            AddTextRow(data, new[] { "Generated by " + page.GeneratedBy + " on " + page.GeneratedAt.ToString("yyyy-MM-dd HH:mm") + " UTC" }, 0);
            AddTextRow(data, new[] { "Filtered records: " + page.TotalCount }, 0);
            foreach (var filter in page.AppliedFilters) AddTextRow(data, new[] { filter.Label + ": " + filter.Value }, 0);
            foreach (var metric in page.Metrics) AddTextRow(data, new[] { metric.Label, metric.Value }, 0);
            foreach (var note in page.CoverageNotes) AddTextRow(data, new[] { "Data coverage", note }, 0);
            if (page.Breakdown.Count > 0)
            {
                AddTextRow(data, new[] { "Summary", "Matching records" }, 1);
                foreach (var group in page.Breakdown) AddTextRow(data, new[] { group.Label, group.Value }, 0);
            }
            AddTextRow(data, table.Headers, 1);
            foreach (var values in table.Rows)
            {
                var row = new Row();
                for (var i = 0; i < values.Count; i++)
                {
                    if (page.Selected?.HasAmount == true && table.Headers[i] == page.Selected.AmountLabel && decimal.TryParse(values[i], NumberStyles.Number, CultureInfo.InvariantCulture, out var number))
                        row.Append(new Cell { DataType = CellValues.Number, CellValue = new CellValue(number.ToString(CultureInfo.InvariantCulture)) });
                    else row.Append(TextCell(values[i], 2));
                }
                data.Append(row);
            }
            workbook.Workbook.Append(new Sheets(new Sheet { Id = workbook.GetIdOfPart(part), SheetId = 1, Name = "Report" }));
            workbook.Workbook.Save();
        }
        return stream.ToArray();
    }

    private static void AddTextRow(SheetData data, IEnumerable<string> values, uint style)
    {
        var row = new Row(); foreach (var value in values) row.Append(TextCell(value, style)); data.Append(row);
    }

    private static Cell TextCell(string value, uint style)
    {
        // Text stays text; also neutralize formula prefixes for downstream spreadsheet tools.
        if (value.TrimStart().Length > 0 && "=+-@".Contains(value.TrimStart()[0])) value = "'" + value;
        return new Cell { DataType = CellValues.InlineString, StyleIndex = style,
            InlineString = new InlineString(new Text(value) { Space = SpaceProcessingModeValues.Preserve }) };
    }
}
